/**
 * PG_CHANGED: environment specific PWA branding.
 *
 * A single build is deployed to every environment, so the icons and the app name of the
 * non-production deployments are picked at runtime from the `pg_environment` key in
 * config.json rather than being baked in at build time.
 *
 * The build ships the icons and the manifest of *every* environment; this module only points
 * the document at the right ones. Both sides of that contract are driven by the table below,
 * which is also imported by `webpack.config.ts` to emit the per-environment manifests.
 */

export interface EnvironmentBranding {
    /** Marker shown on the icons and appended to the app name, e.g. "Beam Gov - BETA". */
    label: string;
    /** Directory the icons of this environment are served from, generated by `scripts/generate-env-icons.sh`. */
    iconsDir: string;
    /** Web app manifest emitted for this environment by the build. */
    manifest: string;
}

/**
 * Branding per `pg_environment` value. Production is deliberately absent: it uses the icons and
 * the app name that are already in the document, so no runtime work is needed for it at all.
 */
export const ENVIRONMENT_BRANDING: Readonly<Record<string, EnvironmentBranding>> = {
    DEV: { label: "DEV", iconsDir: "vector-icons-dev", manifest: "manifest-dev.json" },
    TST: { label: "TST", iconsDir: "vector-icons-tst", manifest: "manifest-tst.json" },
    ACC: { label: "BETA", iconsDir: "vector-icons-acc", manifest: "manifest-acc.json" },
};

/**
 * Look up the branding for an environment.
 *
 * @param environment the `pg_environment` config value, if any
 * @returns the branding, or undefined for production and for unknown values
 */
export function getEnvironmentBranding(environment?: string): EnvironmentBranding | undefined {
    if (!environment) return undefined;

    // `hasOwn` rather than a bare lookup, so that a config value which happens to name something on
    // Object.prototype ("constructor", "toString", ...) is treated as unknown instead of branding
    // the app with a function.
    const name = environment.toUpperCase();
    return Object.hasOwn(ENVIRONMENT_BRANDING, name) ? ENVIRONMENT_BRANDING[name] : undefined;
}

/**
 * Suffix the app name with the environment, e.g. "Beam" becomes "Beam - BETA".
 *
 * Idempotent: an already suffixed name is returned unchanged, because the config is loaded more
 * than once and the page title is rewritten on every room switch.
 *
 * @param name the app name, suffixed or not
 * @param environment the `pg_environment` config value, if any
 * @returns the name, unchanged on production
 */
export function withEnvironmentSuffix(name: string, environment?: string): string {
    const branding = getEnvironmentBranding(environment);
    if (!branding) return name;

    const suffix = ` - ${branding.label}`;
    return name.endsWith(suffix) ? name : name + suffix;
}

/**
 * Point the document at the icons, the manifest and the app name of the given environment, so an
 * installed app or a browser tab shows which environment it is talking to.
 *
 * Does nothing on production, or when the environment is not recognised, leaving the production
 * branding of index.html in place.
 *
 * @param environment the `pg_environment` config value, if any
 */
export function applyEnvironmentBranding(environment?: string): void {
    const branding = getEnvironmentBranding(environment);
    if (!branding) return;

    const manifestLink = document.querySelector<HTMLLinkElement>('link[rel="manifest"]');
    if (manifestLink) {
        manifestLink.href = branding.manifest;
    }

    // Only the icons an installed app uses are branded. The favicons (`rel="icon"`) are left
    // alone: the smallest is 24x24, where the label is an unreadable smudge rather than a marker.
    //
    // index.html points at the production icons, whose file names are content hashed by the
    // build (`vector-icons/120.a2f9942.png`). The icons of the other environments are copied
    // verbatim, so the size in the file name is enough to find the matching one.
    const iconLinks = document.querySelectorAll<HTMLLinkElement>('link[rel~="apple-touch-icon"]');
    for (const link of iconLinks) {
        const size = new URL(link.href, document.baseURI).pathname.split("/").pop()?.split(".")[0];
        if (size && /^\d+$/.test(size)) {
            link.href = `${branding.iconsDir}/${size}.png`;
        }
    }

    // The name of an installed app comes from the manifest, except on iOS and on Windows, which
    // use these instead.
    for (const selector of ['meta[name="apple-mobile-web-app-title"]', 'meta[name="application-name"]']) {
        const meta = document.querySelector<HTMLMetaElement>(selector);
        if (meta) {
            meta.content = withEnvironmentSuffix(meta.content, environment);
        }
    }

    // MatrixChat rewrites the title from the configured brand once it renders, see
    // `setPageSubtitle`; this only covers the time before that happens.
    document.title = withEnvironmentSuffix(document.title, environment);
}
